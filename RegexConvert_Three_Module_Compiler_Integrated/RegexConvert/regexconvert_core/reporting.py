from html import escape
def build_report(data):
    title=escape(str(data.get("title","RegexConvert Session Report")))
    pattern=escape(str(data.get("regex","")))
    results=data.get("results",[])
    rows="".join(f"<tr><td>{escape(str(r.get('string','')))}</td><td>{'Accepted' if r.get('accepted') else 'Rejected'}</td></tr>" for r in results)
    html=f"""<!doctype html><html><head><meta charset="utf-8"><title>{title}</title>
    <style>body{{font-family:'Times New Roman',serif;margin:42px;color:#14243a}}h1{{border-bottom:2px solid #527c78;padding-bottom:12px}}table{{border-collapse:collapse;width:100%}}td,th{{border:1px solid #cbd5df;padding:9px;text-align:left}}th{{background:#e4ece9}}code{{font-family:monospace}}</style></head>
    <body><h1>{title}</h1><p><b>Regular expression:</b> <code>{pattern}</code></p>
    <h2>String validation results</h2><table><thead><tr><th>Input string</th><th>Result</th></tr></thead><tbody>{rows}</tbody></table>
    <p>Generated by RegexConvert.</p></body></html>"""
    return html.encode("utf-8")
